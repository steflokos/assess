package iteration

import (
	"bytes"
	"fmt"
	"strings"

	"go.yaml.in/yaml/v3"

	"github.com/steflokos/assess/internal/model"
)

// CheckText says what is wrong with a note or a name that goes into iterations.yaml. go-yaml writes U+0085, U+2028 and U+2029 as
// they are, and counts them as the end of a line, which an editor does not show and a line by line edit gets wrong.
func CheckText(what, text string) error {
	if i := strings.IndexAny(text, "\u0085\u2028\u2029"); i >= 0 {
		return fmt.Errorf("the %s has a line separator character (U+%04X). Take it out", what, []rune(text[i:])[0])
	}
	return nil
}

// Header starts a new iterations.yaml.
const Header = `# yaml-language-server: $schema=.assess/schema-iterations.json
# The closed iterations of the assessment. assess finalize writes them and assess sign adds signatures.
# Do not edit this file by hand. Each iteration holds the hash of the one before it, so assess verify can find a change.
`

// marshal writes a value as YAML with the indent of the project files.
func marshal(v any) (string, error) {
	var b bytes.Buffer
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return "", err
	}
	if err := enc.Close(); err != nil {
		return "", err
	}
	return b.String(), nil
}

// Entry is the text of one iteration, as an item of the list under iterations:. It ends with a line break.
func Entry(it model.Iteration) (string, error) {
	text, err := marshal(model.Iterations{Iterations: []model.Iteration{it}})
	if err != nil {
		return "", err
	}
	_, rest, _ := strings.Cut(text, "\n") // without the line "iterations:"
	return rest, nil
}

// Append adds an iteration to the text of iterations.yaml. The text is nil for a project that has no iterations yet.
// Everything written before stays, byte for byte, as it was.
func Append(existing []byte, it model.Iteration) ([]byte, error) {
	entry, err := Entry(it)
	if err != nil {
		return nil, err
	}
	if len(bytes.TrimSpace(existing)) == 0 {
		return []byte(Header + "iterations:\n" + entry), nil
	}
	out := append([]byte(nil), existing...)
	if !bytes.HasSuffix(out, []byte("\n")) {
		out = append(out, '\n')
	}
	return append(out, entry...), nil
}

// AddSignature adds a signature to iteration number n, after the last line of that iteration. Every other line stays
// as it is.
func AddSignature(data []byte, n int, s model.Signature) ([]byte, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, err
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) == 0 || doc.Content[0].Kind != yaml.MappingNode {
		return nil, fmt.Errorf("iterations.yaml has no list of iterations")
	}
	var items []*yaml.Node
	m := doc.Content[0]
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == "iterations" && m.Content[i+1].Kind == yaml.SequenceNode {
			items = m.Content[i+1].Content
		}
	}
	at := -1
	for i, item := range items {
		for j := 0; j+1 < len(item.Content); j += 2 {
			if item.Content[j].Value == "number" && item.Content[j+1].Value == fmt.Sprint(n) {
				at = i
			}
		}
	}
	if at < 0 {
		return nil, fmt.Errorf("iterations.yaml has no iteration %d", n)
	}
	lines := strings.Split(strings.TrimSuffix(string(data), "\n"), "\n")
	end := len(lines) // the last line of the iteration, 1-based
	if at+1 < len(items) {
		end = items[at+1].Line - 1
	}
	for end > items[at].Line && (strings.TrimSpace(lines[end-1]) == "" || strings.HasPrefix(strings.TrimSpace(lines[end-1]), "#")) {
		end--
	}
	text, err := marshal([]model.Signature{s})
	if err != nil {
		return nil, err
	}
	var add []string
	has := false
	for j := 0; j+1 < len(items[at].Content); j += 2 {
		has = has || items[at].Content[j].Value == "signatures"
	}
	if !has {
		add = append(add, "    signatures:")
	}
	for _, l := range strings.Split(strings.TrimSuffix(text, "\n"), "\n") {
		add = append(add, "      "+l)
	}
	out := append(append(append([]string(nil), lines[:end]...), add...), lines[end:]...)
	return []byte(strings.Join(out, "\n") + "\n"), nil
}
